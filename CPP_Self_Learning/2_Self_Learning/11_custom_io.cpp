#include <iostream>
using namespace std;

int main() {
    int id;
    string name;
    float salary;

    // Taking input
    cout << "Enter ID: ";
    cin >> id;

    cout << "Enter Name: ";
    cin >> name;

    cout << "Enter Salary: ";
    cin >> salary;

    // Displaying output
    cout << "\n----- Employee Details -----" << endl;
    cout << "ID: " << id << endl;
    cout << "Name: " << name << endl;
    cout << "Salary: " << salary << endl;

    return 0;
}

